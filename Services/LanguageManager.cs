    public string this[string key] => Translate(key);
    public string Translate(string key) =>
        Strings.TryGetValue(key, out var value) ? (_code == "en" ? value.En : value.Cs) : key;
    public static string T(string key) => Current.Translate(key);
    public void SetLanguage(string? code)
    {
        var normalized = string.Equals(code, "en", StringComparison.OrdinalIgnoreCase) ? "en" : "cs";
        var culture = CultureInfo.GetCultureInfo(normalized == "en" ? "en-US" : "cs-CZ");
        CultureInfo.DefaultThreadCurrentCulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
        CultureInfo.CurrentCulture = culture;
        CultureInfo.CurrentUICulture = culture;
        if (_code == normalized) return;
        _code = normalized;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
        LanguageChanged?.Invoke(this, EventArgs.Empty);
    }
